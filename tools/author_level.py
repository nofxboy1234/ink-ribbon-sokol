DOOR_HEIGHT = 2.65
DOOR_THICKNESS = 0.12
DOOR_CENTER_Z = FLOOR_TOP + DOOR_HEIGHT * 0.5


def material(name: str, rgba: tuple[float, float, float, float]):
    result = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    result.diffuse_color = rgba
    return result


MAT_GEO = material("Blockout Grey", (0.43, 0.44, 0.46, 1.0))
MAT_PROP = material("Prop Grey", (0.34, 0.35, 0.37, 1.0))
MAT_WHITE = material("Unlocked White", (0.973, 0.973, 0.949, 1.0))
MAT_PURPLE = material("Dracula Purple", (0.741, 0.576, 0.976, 1.0))
MAT_PINK = material("Dracula Pink", (1.0, 0.475, 0.776, 1.0))
MAT_CYAN = material("Dracula Cyan", (0.545, 0.914, 0.992, 1.0))
MAT_BLUE = material("Ammo Blue", (0.12, 0.43, 0.98, 1.0))
MAT_GREEN = material("Health Green", (0.12, 0.76, 0.30, 1.0))
MAT_ORANGE = material("Breakable Orange", (1.0, 0.42, 0.06, 1.0))


def remove_collection(name: str) -> None:
    collection = bpy.data.collections.get(name)
    if collection is None:
        return
    for obj in list(collection.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    bpy.data.collections.remove(collection)


for collection_name in GENERATED_COLLECTIONS:
    remove_collection(collection_name)


def new_collection(name: str):
    result = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(result)
    return result


GEO = new_collection("Generated_Geometry")
PROPS = new_collection("Generated_Props")
MARKERS = new_collection("Gameplay_Markers")
REFERENCE = bpy.data.collections.get("Authoring_Reference") or new_collection("Authoring_Reference")
REFERENCE.hide_render = True


def move_to_collection(obj, collection) -> None:
    for old in list(obj.users_collection):
        old.objects.unlink(obj)
    collection.objects.link(obj)


def cube(name, location, dimensions, mat=MAT_GEO, collection=GEO, rotation_z=0.0):
    bpy.ops.mesh.primitive_cube_add(location=location, rotation=(0.0, 0.0, rotation_z))
    obj = bpy.context.object
    obj.name = name
    obj.dimensions = dimensions
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    move_to_collection(obj, collection)
    if mat is not None:
        obj.data.materials.append(mat)
    return obj


def empty_cube(name, location, dimensions, collection=MARKERS):
    obj = bpy.data.objects.new(name, None)
    collection.objects.link(obj)
    obj.empty_display_type = "CUBE"
    obj.empty_display_size = 1.0
    obj.location = location
    obj.scale = (dimensions[0] * 0.5, dimensions[1] * 0.5, dimensions[2] * 0.5)
    return obj


def floor_box(name, min_x, max_x, min_y, max_y):
    return cube(
        name,
        ((min_x + max_x) * 0.5, (min_y + max_y) * 0.5, FLOOR_TOP - FLOOR_DEPTH * 0.5),
        (max_x - min_x, max_y - min_y, FLOOR_DEPTH),
    )


def wall_y(name, min_x, max_x, y):
    return cube(name, ((min_x + max_x) * 0.5, y, WALL_CENTER_Z), (max_x - min_x, WALL_THICKNESS, WALL_HEIGHT))


def wall_x(name, x, min_y, max_y):
    return cube(name, (x, (min_y + max_y) * 0.5, WALL_CENTER_Z), (WALL_THICKNESS, max_y - min_y, WALL_HEIGHT))


def doorway_y(prefix, min_x, max_x, y, center_x):
    gap_min = center_x - DOOR_WIDTH * 0.5 - 0.09
    gap_max = center_x + DOOR_WIDTH * 0.5 + 0.09
    wall_y(prefix + "_Left", min_x, gap_min, y)
    wall_y(prefix + "_Right", gap_max, max_x, y)
    lintel_height = WALL_HEIGHT - DOOR_HEIGHT
    cube(
        prefix + "_Lintel",
        (center_x, y, FLOOR_TOP + DOOR_HEIGHT + lintel_height * 0.5),
        (gap_max - gap_min, WALL_THICKNESS, lintel_height),
    )


def prop(name, location, dimensions, rotation_z=0.0):
    return cube(name, location, dimensions, MAT_PROP, PROPS, rotation_z)


def pickup(name, location, mat):
    return cube(name, location, (0.36, 0.36, 0.36), mat, MARKERS)


def breakable(index, location):
    return cube(f"Breakable_ItemBox_{index:02d}", location, (0.84, 0.84, 0.84), MAT_ORANGE, MARKERS)


def door(name, location, mat):
    return cube(name, location, (DOOR_WIDTH, DOOR_THICKNESS, DOOR_HEIGHT), mat, MARKERS)


