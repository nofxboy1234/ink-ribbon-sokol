# Persist the editable scene, then export everything except authoring-only
# references. Selecting explicitly is reliable in headless Blender, whereas
# collection viewport/render visibility is not consistently honored by every
# glTF exporter version.
bpy.ops.wm.save_as_mainfile(filepath=BLEND_PATH)
bpy.ops.object.select_all(action="DESELECT")
reference_objects = set(REFERENCE.objects)
for scene_object in bpy.context.scene.objects:
    if scene_object not in reference_objects:
        scene_object.select_set(True)
bpy.ops.export_scene.gltf(
    filepath=GLB_PATH,
    export_format="GLB",
    use_selection=True,
    export_apply=False,
    export_yup=True,
)
