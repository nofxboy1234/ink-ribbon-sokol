"""Build the playable blockout extension in level/level.blend.

Run with:
  /home/dylan/blender/blender --background level/level.blend --python tools/author_level.py

The existing starting room is preserved.  Everything generated by this script
lives in named collections and can be regenerated without accumulating copies.
"""

